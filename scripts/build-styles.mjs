import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync,mkdirSync,rmSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
mkdirSync(root+'.build',{recursive:true});
execFileSync(process.execPath,[root+'node_modules/@tailwindcss/cli/dist/index.mjs','-i',root+'styles/tailwind.css','-o',root+'.build/ui.css','--minify'],{cwd:root,stdio:'inherit'});
const css=readFileSync(root+'.build/ui.css','utf8');
if(/<\/style/i.test(css))throw new Error('Unsafe stylesheet output');
writeFileSync(root+'src/styles.generated.ts','// Generated by scripts/build-styles.mjs; do not edit.\nexport const stylesheet = '+JSON.stringify(css)+';\n');
rmSync(root+'.build',{recursive:true,force:true});
